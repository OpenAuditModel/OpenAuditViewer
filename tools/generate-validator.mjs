/**
 * Compiles the vendored schema into a standalone validation module.
 *
 * Ajv normally builds its validator at runtime with `new Function`, which a
 * Content-Security-Policy without `'unsafe-eval'` forbids — and the app
 * ships a strict CSP precisely so that no string can ever become code.
 * Precompiling here resolves that without weakening the policy: the
 * generated module is ordinary JavaScript, bundled like any other source
 * file, and the Ajv compiler no longer ships to the user at all.
 *
 * Regenerate whenever the vendored schema changes:
 *   npm run generate-validator      (also runs as part of `npm run build`)
 */
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { _ } from "ajv/dist/compile/codegen/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const viewerRoot = join(import.meta.dirname, "..");
const schemaPath = join(viewerRoot, "src", "schema", "audit-event.schema.json");
const outputPath = join(viewerRoot, "src", "schema", "validate.generated.js");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

// `formats: _\`formats\`` makes the generated code reference a free variable
// named `formats` for format validators; the import prepended below binds it.
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true, formats: _`formats` },
});
addFormats(ajv);

const validate = ajv.compile(schema);
const generated = standaloneCode(ajv, validate);

/*
 * `code.esm` only changes the export syntax; Ajv still emits CommonJS
 * `require(...)` for its own runtime helpers, which no browser can execute.
 * Each one is rewritten to a static import. The pattern is deliberately
 * narrow — a literal module specifier with an optional single member — and
 * the assertion below fails the build if anything it does not understand
 * survives, so this can never silently ship a broken module.
 */
const REQUIRE_CALL = /require\((["'])((?:(?!\1).)+)\1\)(?:\.([A-Za-z_$][\w$]*))?/g;

/** Node resolves a bare subpath exactly; bundlers guess the extension. Be explicit. */
function withExtension(moduleId) {
  return /\.[cm]?js$/.test(moduleId) ? moduleId : `${moduleId}.js`;
}

const bindings = new Map();
const body = generated.replace(REQUIRE_CALL, (_match, _quote, moduleId, member) => {
  const key = `${moduleId}|${member ?? "*"}`;
  let binding = bindings.get(key);
  if (binding === undefined) {
    binding = { name: `ajvRuntime${bindings.size}`, moduleId, member };
    bindings.set(key, binding);
  }
  return binding.name;
});

const runtimeImports = [...bindings.values()].flatMap(({ name, moduleId, member }, index) => {
  const namespace = `ajvModule${index}`;
  const specifier = JSON.stringify(withExtension(moduleId));
  const value =
    member === undefined || member === "default"
      ? `interopDefault(${namespace})`
      : `interopNamed(${namespace}, ${JSON.stringify(member)})`;
  return [`import * as ${namespace} from ${specifier};`, `const ${name} = ${value};`];
});

/*
 * The imported modules are CommonJS, and the two module systems disagree
 * about what their default export is: a bundler honours `__esModule` and
 * hands back `module.exports.default`, while Node hands back
 * `module.exports` itself. Resolving that here — rather than relying on
 * whichever tool happens to load this file — keeps the validator behaving
 * identically under Vite, Vitest and plain Node.
 */
const header = `// GENERATED by tools/generate-validator.mjs — do not edit.
// Standalone Ajv validator for src/schema/audit-event.schema.json, precompiled
// so the app needs no runtime code generation under its Content-Security-Policy.
import * as ajvFormatsModule from "ajv-formats/dist/formats.js";

function interopDefault(namespace) {
  let value = namespace;
  while (value !== null && typeof value === "object" && "default" in value) {
    value = value.default;
  }
  return value;
}

function interopNamed(namespace, name) {
  for (const candidate of [namespace, namespace?.default]) {
    if (candidate !== null && typeof candidate === "object" && name in candidate) {
      return candidate[name];
    }
  }
  throw new Error(\`generated validator: module does not export \${name}\`);
}

const formats = interopNamed(ajvFormatsModule, "fullFormats");
${runtimeImports.join("\n")}
`;

const output = `${header}${body}`;

if (/\brequire\s*\(/.test(body)) {
  throw new Error(
    "generated validator still contains require(); the rewrite pattern needs updating",
  );
}
if (/new Function|eval\(/.test(body)) {
  throw new Error("generated validator contains runtime code generation, which the CSP forbids");
}

writeFileSync(outputPath, output, "utf8");

console.log(
  `wrote ${outputPath} (${Math.round(Buffer.byteLength(output, "utf8") / 1024)} kB, ` +
    `${bindings.size} runtime import${bindings.size === 1 ? "" : "s"})`,
);
